/**
 * ===== 対象エリア 店舗情報取得ワークフロー =====
 * 指定したカテゴリの店舗情報を対象エリア全体で収集する。
 * 実際の処理順序:
 *   1. generateGridList  ... 対象エリア全体をグリッド分割し、「グリッド一覧」シートに座標を保存
 *   2. crawlAllGrids     ... グリッド一覧を巡回して searchNearby を呼び出し、「全飲食店データ」シートに書き込み
 *
 * 参照: Google Maps Platform - Place Types (New) - Food and Drink カテゴリ一覧
 * https://developers.google.com/maps/documentation/places/web-service/place-types
 * (2026-09-10 UTC 時点のドキュメントを参照。includedTypes は Table A のタイプのみ指定可能。
 *  1リクエストの includedTypes は最大50個までという制約があるため、Food and Drink全166種類は
 *  1回のリクエストに収まらない。そのため頻度別に4グループ(A/B/C/D、各50種以内)に分割している。
 *  詳細は lib/catalog/PlaceTypeCatalog.js の TYPE_GROUP_A 〜 D の定義を参照。)
 *
 * ===== グリッドの幾何 =====
 * 対象エリアを GRID_STEP(0.01度)刻みの格子に分割する。「度」で正方形でも実距離では
 * 緯度方向に長い矩形になり、0.01度セルは 1,113m × 902m。セル全体を漏れなく含む円の
 * 半径はその半対角の 717m で、これを cellCoverRadiusMeters が導出する
 * (半径をコードとシートで二重管理しないため、決め打ちの定数は置かない)。
 *
 * 円でセルを覆う以上、円の面積(1.539km²)はセルの面積(1.004km²)の1.53倍あり、
 * 53%は隣接セルとの重複になる。これは正方格子の構造的な下限であり、六方格子
 * (ハニカム配置)にすれば1.21倍まで下げられるが、セル中心が全てずれて進捗を
 * 引き継げないため、移行するなら別プロジェクトとして作り直す必要がある。
 *
 * ===== 密集エリア対策(20件の壁への対応) =====
 * Nearby Search (New) は pageToken (ページング) が非サポートのため、
 * 1回のリクエストで maxResultCount(20件)を超える分は原理的に取得できない。
 * これに対応するため、以下の2段構えの対策を行っている。
 *
 *   (1) 1セルの探索方式(2026-09-20 に「傘型プローブ1コール」へ一本化):
 *
 *       includedTypes は primaryType ではなく place の types 配列全体にマッチする、
 *       という Places API (New) の仕様(2026-09-19 時点、
 *       https://developers.google.com/maps/documentation/places/web-service/nearby-search
 *       の includedTypes の項)を利用すると、'restaurant' のような傘型(umbrella)1つで
 *       primaryType が 'ramen_restaurant' の店もヒットする。そこでプローブ集合
 *       (PLACE_TYPE_PROBE_SET、lib/catalog/PlaceTypeProbeSet.js)で1回だけ検索し、
 *       20件未満(0件を含む)ならそのセルを確定する。20件ちょうど(飽和の疑いがある)
 *       ときは、下記(2)の空間分割(四分木分割)に回す。
 *
 *       かつては頻度別4グループ(A:頻出39種 / B:中頻度41種 / C:やや稀37種 /
 *       D:非常に稀49種)を毎セル無条件に検索し(4コール確定)、20件ちょうど返ってきた
 *       グループだけさらに6種類ずつに細分化して再検索していた(タイプ分割、最大+7コール)。
 *       全域を傘型プローブで実測した結果(docs/survey-findings-2026-09.md 2-5節)、
 *       飽和マス1つあたりのコストは「空間分割=5コール」「タイプ分割=11コール」で
 *       空間分割の方が安いと判明したため、通常経路からはタイプ分割を外し、
 *       プローブ1コール→飽和なら空間分割、に一本化した(lib/crawler/ProbeFirstCellSearch.js)。
 *
 *       166種カタログ・4グループの定義(lib/catalog/PlaceTypeCatalog.js)と、それを使った
 *       探索手順(lib/crawler/TypeGroupCellSearch.js)は削除していない。空間分割でも
 *       解決しない飽和マス(1棟に20店舗以上入っているケースなど)向けのタイプ分割として、
 *       次のステップで再利用する想定(docs/survey-next-actions-2026-09-20.md)。
 *
 *       ----- プローブ集合の検証方法と検証結果 -----
 *       検証は「シート実測が主・API差分は確認用」という順序で行った。理由は、issueが
 *       当初提案していた「密集セルでのAPI差分」だけでは、差分が「プローブ集合の
 *       被覆漏れ」なのか「20件の壁による切り捨て」なのかを区別できないため
 *       (密集セルは定義上 maxResultCount で切り捨てられる)。
 *         1. entrypoints/auditProbeSetCoverage.js(APIコール0) — 旧方式(4グループ)で
 *            毎セル全166タイプを検索していた時代に集めた行は、取りこぼしのない母集団に
 *            なっている(20件の壁に当たった分を除く)。各行の「全タイプ」がプローブ集合と
 *            交差するかを集計すれば、それがそのまま被覆判定になる。
 *         2. entrypoints/compareProbeSetWithTypeGroups.js(5〜25コール) — 1.の裏取りとして、
 *            実際に密集グリッド1つでプローブ集合とA/B/C/Dの両方を叩き、Place ID差分を
 *            確認する。
 *       検証結果(導出日 / 母集団行数 / 被覆率 / 未観測タイプ一覧)は
 *       lib/catalog/PlaceTypeProbeSet.js の冒頭コメントに固定して記録する
 *       (このファイルの重複管理を避けるため、ここには転記しない)。
 *       ただし独立検証としての規模はAPI差分(2.)の母集団60件にとどまる。シート実測
 *       (1.)による被覆率100%はプローブ集合自身の結果に対する自己参照であり、地域全体の
 *       網羅率を意味しない。詳細はdocs/survey-next-actions-2026-09-20.md 2-1節を参照。
 *
 *       ----- 監査の自己循環に関する注意(最重要) -----
 *       auditProbeSetCoverage の証拠能力は「旧方式(4グループ)で集めた行」に由来する。
 *       通常経路をプローブ集合に統一した現在、新しく集まる行はプローブ集合に一致する
 *       ものだけになるため、この監査を再度回すと被覆率が意味もなく100%に近づいて見える
 *       (自己循環)。この監査は**旧方式のデータに対して実行して根拠を確定させるための
 *       もの**であり、切替後に集まった行の定点観測には使えない。切替後の被覆漏れ検知は
 *       lib/crawler/ProbeFirstCellSearch.js が担う(新規取得placeの全件に
 *       isCoveredByProbeSet をかけ、falseなら警告ログと stats.uncoveredPlaces に計上する。
 *       飽和・非飽和を問わず全件チェックするため、運用中に追加コールなしで穴が
 *       表面化する)。
 *
 *   (2) セルの四分木分割: プローブがちょうど20件返ってきたセルは、その矩形を4象限に
 *       等分し、各象限の外接円を検索範囲とする子グリッドを「グリッド一覧」に追加する
 *       (階層+1)。矩形は隙間なく分割できるため被覆漏れが原理的に発生せず、1階層ごとに
 *       半径がちょうど半分になる(717 → 359 → 180 → 90m)。
 *       階層が MAX_TIER に達してもまだ20件出る場合は、これ以上の自動化は
 *       行わず「要確認(上限到達)」フラグを立てて人間の目視確認に委ねる。
 *
 *       旧実装は「親の円」を半径0.6倍の4つの円で覆おうとしていたが、子の中心が
 *       親中心から0.707R離れているのに子半径が0.6Rしかなく、親中心に半径75mの穴が空き
 *       親円の約4.5%が未被覆だった。密集セルの最も濃い中心部が抜け落ちていたため、
 *       矩形ベースの四分木に置き換えている。
 *
 * 上記の対策をもってしても、Googleのデータベースに未掲載の店や、
 * それでも取りこぼす極端な密集地は残り得る。完全網羅ではなく
 * 「現実的に拾える範囲を最大化する」ことがゴールである点に留意。
 *
 * ===== 自前の月間APIコール上限(2026-09-17 追加) =====
 * Google Cloud側の割り当て(Quotas)設定は反映にタイムラグがあるため、
 * それとは別にスクリプトプロパティで月間コール数を自前管理し、
 * MONTHLY_API_CALL_LIMIT に達したら callSearchNearby がAPIを叩く前に
 * 自ら停止する二重の安全策を入れている。月が変わると自動的にリセットされる。
 *
 * カウントは「実際に叩く前」に加算する(暴走を確実に止めるにはこの順序でなければならない)。
 * ただしそれだけだと、Google 側のクォータで 429 になった分まで自前の枠を消費してしまう。
 * 429(RESOURCE_EXHAUSTED)はリクエストが処理されていない = 課金対象外なので、
 * refundApiQuota で1件だけ戻す。戻すのはクォータ起因の拒否に限り、他のエラーは
 * 課金の有無が自明でないうえ戻すと暴走時に上限が効かなくなるため数えたままにする。
 *
 * なお GCP 側には別途 SearchNearbyRequestPerDayPerProject(日次)の割り当てがあり、
 * この枠は自前の月間上限とは独立に効く。日次クォータを使い切った状態で日次トリガーが
 * 走ると、1コール目が 429 で弾かれてその実行は何も進まない(上の返却処理がなければ、
 * その1件が毎日ぶん月間枠から消えていた)。日次クォータの窓は UTC 07:00 起点
 * (米国太平洋時間の深夜)で、日本時間では16:00にリセットされる。
 *
 * crawlAllGrids は実行の最後に「プローブ内訳」(コール数・0件セル数・確定セル数・
 * 20件飽和(空間分割対象)セル数・階層別の消費・プローブ集合で被覆されなかった店の数)を
 * ログに出す。格子方式の変更判断や被覆漏れの監視に使う計測値。
 *
 * ===== 調査と収穫で無料枠を分ける(2026-09-20 追加) =====
 * Places API (New) の無料枠は課金SKUごとに別勘定で、Pro は 5,000/月、Enterprise は
 * 1,000/月。SKUは fieldMask の中身で決まる。
 *
 * 従来は全てのコールを Enterprise の fieldMask で打っていたため、「どう割れば20件に
 * 収まるか」の試行錯誤(4グループ・タイプ分割・四分木の探り)まで営業用の1,000枠を
 * 食っていた。2026-09-20 の実測では、全コールの50%がタイプ分割、35%がB/C/Dだった。
 *
 * そこで用途で枠を分ける:
 *   調査 … PLACE_SURVEY_FIELD_MASK(Pro段のみ。id/types/location など)で 5,000/月
 *   収穫 … PLACE_SEARCH_FIELD_MASK(Enterprise段。rating/websiteUri など)で 1,000/月
 *
 * SKUは呼び出し側に指定させず apiSkuOfFieldMask が fieldMask から導出する。マスクと
 * SKUを別々に持つと取り違えたときに枠を誤って消費するため。未知のマスクは安全側
 * (Enterprise)に倒す。
 *
 * ===== 実態を先に測ってからアルゴリズムを決める(2026-09-20 追加) =====
 * 分割方式(カテゴリの粒度・エリアの粒度)を机上で決めるのをやめ、Pro枠の実測から
 * 決める。entrypoints/surveyAllCells.js が全マスに傘型プローブを1コールずつ投げ、
 * 次の3つを集める。営業用の Enterprise枠は1コールも使わない。
 *
 *   1. マスごとの正確な店舗数 … 20件未満なら実数、20件なら「要分割」が確定する
 *   2. 本当に空のマス … 探索対象から恒久的に外せるかを Google の答えで判断する
 *   3. タイプの実測 … 1マス最大20件ぶんの types。全域で数千件になり、
 *      「166種のうちこの地域に実在するのは何種か」を刈り込みの根拠にできる
 *
 * 飽和しても分割や再検索はしない。ここで知りたいのは「20件を超えるか」までで、
 * 超えた先の内訳は分割方式を決めてから取りに行けばよい。
 *
 * 調査結果は「調査(マス)」「調査(店)」シートに書き、本番の「全飲食店データ」には
 * 触れない。Pro段には rating も websiteUri も無いため、本番に混ぜると評価とHPが
 * 空の行ができ、Place ID の重複除去で二度と営業データを取りに行けなくなる。
 *
 * ===== 探索範囲を外部データで絞る(2026-09-20 追加) =====
 * OpenStreetMap の Overpass API はキーもコストも不要で、Google のクォータを1回も
 * 使わずに「どのセルに店があるか」の当たりを付けられる。対象エリアの飲食系POIは
 * 2,515件で、374マスのうち矩形基準で180マス(48%)、検索円まで含めても154マスに
 * POIが1件も無かった。
 *
 * ただしOSMの網羅性はGoogleに劣るため、0件だけを根拠にセルを捨てるのは危険。
 * entrypoints/surveyEmptyCells.js が Pro枠で1セル1コールずつ裏を取る
 * (154コールはPro枠5,000の3%で、営業用の枠は一切消費しない)。
 *
 * OSMの取得はローカルで行い、結果だけを lib/survey/EmptyCellPrediction.js という
 * ソースにして clasp push で持ち込む。当初は GAS から直接 Overpass を叩いていたが、
 * UrlFetchApp からは到達できなかった("Address unavailable"。共用サーバーが
 * データセンターからのアクセスを弾いていると思われる)。結果として GAS は実行時に
 * Google 以外のネットワークへ出ない構成になり、外部サービスの停止や仕様変更で
 * クロールが止まるリスクも消えた。
 *
 * ===== 出力シートのフィルタを毎回作り直さない(2026-09-20 追加) =====
 * 「全飲食店データ」シートのフィルタは、範囲が意図とずれたときだけ張り直す
 * (lib/crawler/PlaceDataSheetFilter.js)。以前は crawlAllGrids の末尾で毎回
 * remove() → createFilter() しており、createFilter() は条件なしのフィルタを張るため、
 * 運用者が設定した絞り込み条件(HP種別=なし / 評価>=3.8 等)が日次トリガーのたびに
 * 消えていた。クロールが全域を巡り終えるまで数ヶ月かかるので、その間ずっと
 * 「毎朝フィルタを設定し直す」運用コストが発生していた。
 *
 * 範囲を getLastRow() ではなく getMaxRows() で張ることで、行が増えても意図する範囲が
 * 変わらず、張り直し自体が不要になる。あわせて PlaceRowWriter がシートの行容量を
 * 見るようにした。既定1000行を超える範囲へ setValues すると GAS が例外を投げてクロール
 * ごと落ちるためで、行の追加は PLACE_DATA_ROW_CAPACITY_CHUNK 行単位にまとめ、
 * 範囲変更(=フィルタの張り直し)の頻度を下げている。
 */
